//! Wire format: data frames, control messages, path and header rules, backoff.

use serde::{Deserialize, Serialize};
use std::time::Duration;

pub const FLAG_TEXT: u8 = 0x01;
pub const FLAG_MORE: u8 = 0x02;
pub const HEADER_LEN: usize = 5;

/// Encodes a data frame: id (u32 BE), flags, payload.
pub fn encode_frame(id: u32, flags: u8, payload: &[u8]) -> Vec<u8> {
    let mut v = Vec::with_capacity(HEADER_LEN + payload.len());
    v.extend_from_slice(&id.to_be_bytes());
    v.push(flags);
    v.extend_from_slice(payload);
    v
}

#[derive(Debug, PartialEq, Eq)]
pub enum FrameError {
    TooShort,
    TooLarge,
    BadFlags,
}

/// Decodes a data frame, enforcing `max_frame` and the reserved flag bits.
pub fn decode_frame(buf: &[u8], max_frame: usize) -> Result<(u32, u8, &[u8]), FrameError> {
    if buf.len() < HEADER_LEN {
        return Err(FrameError::TooShort);
    }
    if buf.len() - HEADER_LEN > max_frame {
        return Err(FrameError::TooLarge);
    }
    let id = u32::from_be_bytes([buf[0], buf[1], buf[2], buf[3]]);
    let flags = buf[4];
    if flags & !(FLAG_TEXT | FLAG_MORE) != 0 {
        return Err(FrameError::BadFlags);
    }
    Ok((id, flags, &buf[HEADER_LEN..]))
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ServiceDecl {
    pub name: String,
    pub kind: String,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(default)]
pub struct Limits {
    pub max_streams: usize,
    pub max_frame: usize,
    pub initial_window: u64,
    pub max_header_bytes: usize,
    pub max_message: usize,
    pub max_services: usize,
}

impl Default for Limits {
    fn default() -> Self {
        Limits {
            max_streams: 16,
            max_frame: 65536,
            initial_window: 262_144,
            max_header_bytes: 16_384,
            max_message: 8 * 1024 * 1024,
            max_services: 16,
        }
    }
}

pub type Headers = Vec<(String, String)>;

/// Control messages received from the instance.
#[derive(Debug, Deserialize)]
#[serde(tag = "t", rename_all = "lowercase")]
pub enum Incoming {
    Welcome {
        #[serde(default)]
        v: u32,
        #[serde(default = "default_ping")]
        ping_interval: u64,
        #[serde(default)]
        limits: Limits,
    },
    Open {
        id: u32,
        service: String,
        proto: String,
        #[serde(default)]
        method: String,
        path: String,
        #[serde(default)]
        headers: Headers,
    },
    End {
        id: u32,
    },
    Error {
        id: u32,
        #[serde(default)]
        code: String,
        #[serde(default)]
        message: String,
    },
    Window {
        id: u32,
        add: u64,
    },
    Ping {
        n: u64,
    },
    Pong {
        #[serde(default)]
        n: u64,
    },
    Bye {
        #[serde(default)]
        code: String,
        #[serde(default)]
        message: String,
    },
}

fn default_ping() -> u64 {
    15
}

/// Control messages sent by the agent.
#[derive(Debug, Serialize)]
#[serde(tag = "t", rename_all = "lowercase")]
pub enum Outgoing<'a> {
    Hello {
        v: u32,
        agent: &'a str,
        services: &'a [ServiceDecl],
    },
    Head {
        id: u32,
        status: u16,
        headers: &'a Headers,
    },
    End {
        id: u32,
    },
    Error {
        id: u32,
        code: &'a str,
        message: &'a str,
    },
    Window {
        id: u32,
        add: u64,
    },
    Pong {
        n: u64,
    },
}

impl Outgoing<'_> {
    pub fn to_text(&self) -> String {
        serde_json::to_string(self).expect("serializable message")
    }
}

/// Rules of section 4.1 for `path`, re-validated by the agent.
pub fn valid_path(p: &str) -> bool {
    p.starts_with('/')
        && !p.starts_with("//")
        && p.len() <= 2048
        && !p.contains("..")
        && !p.chars().any(|c| c.is_control() || c == ' ' || c == '\\')
}

const HOP_BY_HOP: &[&str] = &[
    "connection",
    "upgrade",
    "keep-alive",
    "transfer-encoding",
    "te",
    "trailer",
    "host",
    "content-length",
];

pub fn is_hop_by_hop(name: &str) -> bool {
    let n = name.to_ascii_lowercase();
    HOP_BY_HOP.contains(&n.as_str()) || n.starts_with("proxy-")
}

/// Request headers forwarded to a local HTTP service.
pub fn forward_headers(h: &Headers) -> Headers {
    h.iter()
        .filter(|(k, _)| !is_hop_by_hop(k))
        .cloned()
        .collect()
}

/// Request headers forwarded to a local WebSocket service (handshake headers are
/// generated by the client, `origin` is replaced).
pub fn forward_ws_headers(h: &Headers) -> Headers {
    h.iter()
        .filter(|(k, _)| {
            let n = k.to_ascii_lowercase();
            !is_hop_by_hop(&n) && !n.starts_with("sec-websocket-") && n != "origin"
        })
        .cloned()
        .collect()
}

/// Reconnection delay: 1 s doubling to 60 s, `r` in [0,1) gives -20%..+20% jitter.
pub fn backoff(attempt: u32, r: f64) -> Duration {
    let base = (1u64 << attempt.min(6)).min(60) as f64;
    Duration::from_secs_f64((base * (0.8 + 0.4 * r.clamp(0.0, 1.0))).max(0.5))
}

/// Clamp-free pseudo random in [0,1) from the clock (no `rand` dependency needed).
pub fn jitter() -> f64 {
    let n = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.subsec_nanos())
        .unwrap_or(0);
    (n % 1000) as f64 / 1000.0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn frame_roundtrip() {
        let f = encode_frame(0x0102_0304, FLAG_TEXT | FLAG_MORE, b"abc");
        assert_eq!(&f[..5], &[1, 2, 3, 4, 3]);
        let (id, fl, p) = decode_frame(&f, 65536).unwrap();
        assert_eq!((id, fl, p), (0x0102_0304, 3, &b"abc"[..]));
    }

    #[test]
    fn frame_rejections() {
        assert_eq!(decode_frame(&[0, 0, 0], 10), Err(FrameError::TooShort));
        assert_eq!(
            decode_frame(&encode_frame(1, 4, b""), 10),
            Err(FrameError::BadFlags)
        );
        assert_eq!(
            decode_frame(&encode_frame(1, 0, &[0; 11]), 10),
            Err(FrameError::TooLarge)
        );
        assert!(decode_frame(&encode_frame(1, 0, &[0; 10]), 10).is_ok());
    }

    #[test]
    fn paths() {
        assert!(valid_path("/api/kernels?x=1"));
        for bad in [
            "api",
            "//x",
            "/a/../b",
            "/a b",
            "/a\\b",
            "/a\nb",
            &format!("/{}", "a".repeat(2048)),
        ] {
            assert!(!valid_path(bad), "{bad}");
        }
    }

    #[test]
    fn headers_filtered() {
        let h: Headers = vec![
            ("host".into(), "x".into()),
            ("connection".into(), "upgrade".into()),
            ("proxy-authorization".into(), "x".into()),
            ("authorization".into(), "token t".into()),
            ("origin".into(), "https://i".into()),
            ("sec-websocket-key".into(), "k".into()),
        ];
        assert_eq!(forward_headers(&h).len(), 3);
        let w = forward_ws_headers(&h);
        assert_eq!(
            w,
            vec![("authorization".to_string(), "token t".to_string())]
        );
    }

    #[test]
    fn backoff_grows_and_caps() {
        assert_eq!(backoff(0, 0.5), Duration::from_secs(1));
        assert_eq!(backoff(1, 0.5), Duration::from_secs(2));
        assert_eq!(backoff(5, 0.5), Duration::from_secs(32));
        assert_eq!(backoff(6, 0.5), Duration::from_secs(60));
        assert_eq!(backoff(40, 0.5), Duration::from_secs(60));
        assert!(backoff(3, 0.0) < backoff(3, 0.999));
    }

    #[test]
    fn parses_messages() {
        let m: Incoming = serde_json::from_str(r#"{"t":"open","id":7,"service":"j","proto":"http","method":"GET","path":"/a","headers":[["a","b"]]}"#).unwrap();
        assert!(matches!(m, Incoming::Open { id: 7, .. }));
        let w: Incoming = serde_json::from_str(
            r#"{"t":"welcome","v":1,"ping_interval":15,"limits":{"max_frame":1000}}"#,
        )
        .unwrap();
        match w {
            Incoming::Welcome { limits, .. } => {
                assert_eq!(limits.max_frame, 1000);
                assert_eq!(limits.initial_window, 262_144);
            }
            _ => panic!(),
        }
        assert!(serde_json::from_str::<Incoming>(r#"{"t":"zzz"}"#).is_err());
    }
}
