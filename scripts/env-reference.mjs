#!/usr/bin/env node
// Référence des variables d'environnement : source unique docs/env-vars.json.
//   node scripts/env-reference.mjs --write   régénère .env.example et les pages de doc (FR et EN)
//   node scripts/env-reference.mjs --check   CI : échoue si une variable lue dans le code n'est pas documentée (ou
//                                            l'inverse), ou si les fichiers générés ne sont pas à jour
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const rel = (p) => path.join(root, p)
const data = JSON.parse(fs.readFileSync(rel('docs/env-vars.json'), 'utf8'))
const vars = data.vars

// --- Sortie ---------------------------------------------------------------

function envExample() {
  const lines = ['# Réglages de l\'instance Looty. Fichier généré par scripts/env-reference.mjs à partir de docs/env-vars.json :', '# modifier la source, pas ce fichier. Référence complète : https://looty.untypequicode.fr/fr/docs/reference/environment/', '']
  for (const [g, label] of Object.entries(data.groups)) {
    const list = vars.filter((v) => v.group === g && v.env_example !== 'none')
    if (!list.length) continue
    lines.push(`# --- ${label.fr} ---`)
    for (const v of list) {
      lines.push(...v.fr.match(/.{1,110}(\s|$)/g).map((l) => `# ${l.trim()}`))
      lines.push(`${v.env_example === 'active' ? '' : '# '}${v.name}=${v.env_example === 'active' ? v.value ?? '' : v.example}`)
    }
    lines.push('')
  }
  lines.push('# Avec le fournisseur inclus (Pocket ID, fichiers *.pocket-id.*), remplacez le bloc OIDC par :')
  lines.push('#   AUTH_DOMAIN=auth.looty.example.org          # sous-domaine dédié, son DNS pointe vers ce serveur')
  lines.push('#   OIDC_ISSUER=https://auth.looty.example.org  # https:// + AUTH_DOMAIN')
  lines.push('#   OIDC_CLIENT_ID=looty')
  lines.push('#   OIDC_CLIENT_SECRET=                          # openssl rand -hex 32')
  lines.push('#   OIDC_PROVIDER_ID=                            # uuidgen (obligatoire ici)')
  lines.push('#   POCKET_ID_ENCRYPTION_KEY=                    # openssl rand -base64 32')
  lines.push('#   POCKET_ID_STATIC_API_KEY=                    # openssl rand -hex 32')
  lines.push('')
  return lines.join('\n')
}

const yes = { en: 'yes', fr: 'oui' }, no = { en: 'no', fr: 'non' }
function page(lang) {
  const en = lang === 'en'
  const cell = (s) => String(s).replace(/\|/g, '\\|')
  const req = (v) => (v.required === 'yes' ? yes[lang] : v.required === 'no' ? no[lang] : v.required)
  const scopeNames = { backend: 'backend', frontend: en ? 'web interface' : 'interface web', collaboration: en ? 'collaboration' : 'collaboration', compose: 'docker compose' }
  const out = [
    '---',
    `title: ${JSON.stringify(en ? 'Environment variables' : 'Variables d’environnement')}`,
    `description: ${JSON.stringify(en ? 'Every environment variable of the Looty backend, web interface and collaboration service: role, default, required or not, example and version.' : 'Toutes les variables d’environnement du backend, de l’interface web et du service de collaboration de Looty : rôle, valeur par défaut, obligatoire ou non, exemple et version.')}`,
    '---',
    '',
    en ? '<!-- Generated by scripts/env-reference.mjs from docs/env-vars.json. Do not edit by hand. -->' : '<!-- Généré par scripts/env-reference.mjs à partir de docs/env-vars.json. Ne pas modifier à la main. -->',
    '',
    en
      ? 'Settings go in the `.env` file next to your compose file. The **Compose** column says whether the official compose files pass the variable from `.env` to the container; for the others, add them under `environment:` of the service in a `docker-compose.override.yml`. A variable left empty counts as unset.'
      : 'Les réglages se font dans le fichier `.env`, à côté du fichier compose. La colonne **Compose** indique si les fichiers compose officiels transmettent la variable de `.env` au conteneur ; pour les autres, ajoutez-la sous `environment:` du service dans un `docker-compose.override.yml`. Une variable vide compte comme non définie.',
    '',
    en ? 'This page is generated from `docs/env-vars.json` and checked in CI against the code: adding a variable without documenting it fails the build.' : 'Cette page est générée à partir de `docs/env-vars.json` et vérifiée en CI contre le code : ajouter une variable sans la documenter fait échouer la CI.',
    '',
  ]
  for (const [g, label] of Object.entries(data.groups)) {
    const list = vars.filter((v) => v.group === g)
    if (!list.length) continue
    out.push(`## ${label[lang]}`, '')
    out.push(en ? '| Variable | Service | Role | Default | Required | Example | Since | Compose |' : '| Variable | Service | Rôle | Défaut | Obligatoire | Exemple | Depuis | Compose |')
    out.push('|---|---|---|---|---|---|---|---|')
    for (const v of list) {
      const scope = v.scope.split(', ').map((s) => scopeNames[s]).join(', ')
      out.push(`| \`${v.name}\` | ${scope} | ${cell(v[lang])} | ${v.default === '' ? '–' : '`' + cell(v.default) + '`'} | ${cell(req(v))} | ${v.example === '' ? '–' : '`' + cell(v.example) + '`'} | ${v.since} | ${v.compose ? yes[lang] : no[lang]} |`)
    }
    out.push('')
  }
  return out.join('\n')
}

const outputs = {
  '.env.example': envExample(),
  'site/web/src/content/docs/docs/reference/environment.md': page('en'),
  'site/web/src/content/docs/fr/docs/reference/environment.md': page('fr'),
}

// --- Contrôle du code -----------------------------------------------------
function walk(dir, ok) {
  const found = []
  for (const e of fs.readdirSync(rel(dir), { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === 'target' || e.name.startsWith('.')) continue
    const p = path.join(dir, e.name)
    if (e.isDirectory()) found.push(...walk(p, ok))
    else if (ok(p)) found.push(p)
  }
  return found
}
// Variables du système, pas des réglages de Looty.
const system = new Set(['PATH', 'HOME', 'TEXMFVAR', 'NODE_ENV', 'RUST_LOG'])
function codeVars() {
  const names = new Map()
  const add = (n, f) => { if (!system.has(n)) (names.get(n) || names.set(n, []).get(n)).push(f) }
  const rs = walk('backend/src', (p) => p.endsWith('.rs'))
  for (const f of rs) {
    for (const m of fs.readFileSync(rel(f), 'utf8').matchAll(/(?<![A-Za-z0-9_])(?:env::var(?:_os)?|var|mb|env_[a-z0-9]+)\(\s*"([A-Z][A-Z0-9_]{2,})"/g)) add(m[1], f)
  }
  const js = [...walk('collaboration', (p) => /\.(js|mjs|ts)$/.test(p) && !/\.test\./.test(p)), ...walk('frontend/server', (p) => /\.ts$/.test(p)), 'frontend/nuxt.config.ts']
  for (const f of js) for (const m of fs.readFileSync(rel(f), 'utf8').matchAll(/process\.env\.([A-Z][A-Z0-9_]+)/g)) add(m[1], f)
  return names
}

const mode = process.argv[2]
if (mode === '--write') {
  for (const [f, text] of Object.entries(outputs)) { fs.mkdirSync(path.dirname(rel(f)), { recursive: true }); fs.writeFileSync(rel(f), text) }
  console.log('Généré :', Object.keys(outputs).join(', '))
} else if (mode === '--check') {
  const errors = []
  const code = codeVars(), doc = new Map(vars.map((v) => [v.name, v]))
  for (const [n, files] of code) if (!doc.has(n)) errors.push(`${n} est lue dans le code (${[...new Set(files)].join(', ')}) mais absente de docs/env-vars.json`)
  for (const v of vars) if (v.scope !== 'compose' && !code.has(v.name)) errors.push(`${v.name} est documentée mais plus lue dans le code (backend/src, collaboration, frontend)`)
  for (const v of vars) for (const k of ['name', 'scope', 'group', 'required', 'since', 'en', 'fr']) if (v[k] === undefined || v[k] === '') errors.push(`${v.name} : champ « ${k} » manquant`)
  for (const [f, text] of Object.entries(outputs)) if (!fs.existsSync(rel(f)) || fs.readFileSync(rel(f), 'utf8') !== text) errors.push(`${f} n'est pas à jour : node scripts/env-reference.mjs --write`)
  if (errors.length) { console.error(errors.map((e) => '✗ ' + e).join('\n')); process.exit(1) }
  console.log(`OK : ${vars.length} variables documentées, ${code.size} lues dans le code.`)
} else { console.error('Usage : node scripts/env-reference.mjs --write | --check'); process.exit(2) }
