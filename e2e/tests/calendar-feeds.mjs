import { B, OUT, ok, launch, login, api as call } from '../lib/index.mjs'
const { browser, page: p, errors } = await launch(1400, 950)
await login(p)
const api = (path, method, body) => call(p, path, method, body)
// Espace dédié : le test ne dépend pas de celui de run.mjs.
const { workspace } = await api('/api/workspaces', 'POST', { name: 'Feeds ' + Date.now() })
await api(`/api/workspaces/${workspace.id}/events`, 'POST', { title: 'Feed event', all_day: false, start: new Date(Date.now() + 86400000).toISOString(), end: new Date(Date.now() + 90000000).toISOString() })
await p.goto(`${B}/w/${workspace.id}/settings/calendars`, { waitUntil: 'networkidle' }); await p.waitForTimeout(800)
ok('feeds section shown', (await p.getByText(/Nouveau flux d’abonnement|New subscription feed/).count()) > 0)
await p.getByRole('button', { name: /Nouveau flux d’abonnement|New subscription feed/ }).click(); await p.waitForTimeout(300)
await p.getByRole('dialog').locator('input').first().fill('Infomaniak')
await p.getByRole('dialog').getByRole('button', { name: /^(Créer|Create)$/ }).click(); await p.waitForTimeout(800)
const url = await p.locator('.token code').first().innerText()
ok('url shown', /\/api\/ics\/looty_[0-9a-f]+\.ics$/.test(url), url)
const hrefs = await p.locator('a.target').evaluateAll((as) => as.map((a) => a.href))
ok('3 subscribe buttons', hrefs.length === 3 && hrefs[0].startsWith('https://calendar.google.com/calendar/r?cid=webcal') && hrefs[1].startsWith('webcal://') && hrefs[2].includes('outlook'), hrefs.join(' | '))
await p.screenshot({ path: OUT + 'feeds-created.png' })
const body = await (await p.request.get(url)).text()
ok('feed has the event', body.includes('BEGIN:VCALENDAR') && body.includes('Feed event'))
await p.getByRole('dialog').getByRole('button', { name: /Terminé|Done/ }).click(); await p.waitForTimeout(500)
ok('listed after creation', (await p.getByText('Infomaniak').count()) > 0)
await p.getByRole('button', { name: /Révoquer|Revoke/ }).first().click(); await p.waitForTimeout(400)
await p.getByRole('alertdialog').or(p.getByRole('dialog')).getByRole('button', { name: /Révoquer|Revoke/ }).last().click(); await p.waitForTimeout(800)
ok('revoked feed answers 404', (await p.request.get(url)).status() === 404)
ok('no page errors', errors.length === 0, errors.join(' | '))
await browser.close()
